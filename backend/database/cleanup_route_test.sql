    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='테스트 데이터 식별 정보가 다름. 삭제를 중단함.';
  END IF;
  IF EXISTS (
    SELECT 1 FROM flight f WHERE f.flight_id IN (871001,871002,871003,871004,871005,871006,871007,871008,871009,871010,871011,871012,871013,871014,871015,871016,871017) AND NOT EXISTS (
