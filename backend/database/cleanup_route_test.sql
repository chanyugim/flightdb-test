  END IF;
  IF EXISTS (SELECT 1 FROM member_account WHERE member_id IN ('ux26_member_a','ux26_member_b','ux26_new','ux26_admin') AND name NOT LIKE '[UX26]%')
     OR EXISTS (SELECT 1 FROM reservation WHERE reservation_no IN ('UX26R001','UX26R002','UX26R003','UX26R004','UX26R005','UX26R006','UX26R007','UX26R008','UX26R009','UX26R010','UX26R011','UX26R012','UX26R013','UX26R014','UX26R015','UX26R016') AND (booker_name NOT LIKE '[UX26]%' OR booker_email NOT LIKE '%@example.invalid'))
